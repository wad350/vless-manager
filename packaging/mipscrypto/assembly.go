package main

import (
	"fmt"
	"strings"
)

//go:generate sh -c "cd ../.. && go run ./packaging/mipscrypto -generate"

// Interleave independent columns to avoid serial dependencies on the 1004Kc.
func assemblySource() string {
	var out strings.Builder
	out.WriteString(`// Code generated by go run ./packaging/mipscrypto -generate; DO NOT EDIT.
//go:build linux && mipsle && gc && !purego

#include "textflag.h"

// R1..R16 = state, R17 = initial state, R18 = dst, R19 = src,
// R20 = public round counter, R21 = scratch. R22/R23/R30 are untouched.
`)
	writeBlockAssembly(&out, false)
	writeBlockAssembly(&out, true)
	return out.String()
}

func writeBlockAssembly(out *strings.Builder, batch bool) {
	name, size := "xorBlockMIPS32R2", 12
	if batch {
		name, size = "xorBlocksMIPS32R2", 16
		out.WriteString("\n// R24 = public block count, R25 = counter. Input state is immutable.\n")
	}
	fmt.Fprintf(out, "TEXT ·%s(SB), NOSPLIT, $-4-%d\n", name, size)
	out.WriteString(`	MOVW state+0(FP), R17
	MOVW dst+4(FP), R18
	MOVW src+8(FP), R19
`)
	if batch {
		out.WriteString(`	MOVW blocks+12(FP), R24
	BEQ R24, finished
	MOVW 48(R17), R25
blocks:
`)
	}
	for i := 0; i < 16; i++ {
		if batch && i == 12 {
			out.WriteString("\tMOVW R25, R13\n")
		} else {
			fmt.Fprintf(out, "\tMOVW %d(R17), R%d\n", i*4, i+1)
		}
	}
	out.WriteString("\tMOVW $10, R20\nrounds:\n")
	groups := [2][4][4]int{
		{{0, 4, 8, 12}, {1, 5, 9, 13}, {2, 6, 10, 14}, {3, 7, 11, 15}},
		{{0, 5, 10, 15}, {1, 6, 11, 12}, {2, 7, 8, 13}, {3, 4, 9, 14}},
	}
	steps := []struct {
		op    string
		left  int
		right int
		shift int
	}{
		{"ADDU", 1, 0, 0}, {"XOR", 0, 3, 0}, {"ROTR", 3, 3, 16},
		{"ADDU", 3, 2, 0}, {"XOR", 2, 1, 0}, {"ROTR", 1, 1, 20},
		{"ADDU", 1, 0, 0}, {"XOR", 0, 3, 0}, {"ROTR", 3, 3, 24},
		{"ADDU", 3, 2, 0}, {"XOR", 2, 1, 0}, {"ROTR", 1, 1, 25},
	}
	for _, group := range groups {
		for _, step := range steps {
			for _, quarter := range group {
				if step.op == "ROTR" {
					fmt.Fprintf(out, "\tROTR $%d, R%d\n", step.shift, quarter[step.right]+1)
				} else {
					fmt.Fprintf(out, "\t%s R%d, R%d\n", step.op, quarter[step.left]+1, quarter[step.right]+1)
				}
			}
		}
	}
	out.WriteString("\tSUBU $1, R20\n\tBNE R20, rounds\n\n")
	// Pointer alignment is public; aligned loads/stores need half the memory ops.
	out.WriteString("\tOR R18, R19, R21\n\tAND $3, R21\n\tBNE R21, unaligned\n")
	writeBlockOutput(out, batch, true)
	out.WriteString("\tJMP output_done\nunaligned:\n")
	writeBlockOutput(out, batch, false)
	out.WriteString("output_done:\n")
	if batch {
		out.WriteString(`	ADDU $64, R18
	ADDU $64, R19
	ADDU $1, R25
	SUBU $1, R24
	BNE R24, blocks
finished:
`)
	}
	out.WriteString("\tRET\n")
}

func writeBlockOutput(out *strings.Builder, batch, aligned bool) {
	for i := 0; i < 16; i++ {
		offset := i * 4
		if aligned {
			if batch && i == 12 {
				out.WriteString("\tMOVW R25, R20\n")
			} else {
				fmt.Fprintf(out, "\tMOVW %d(R17), R20\n", offset)
			}
			// Independent loads cover load-use latency without adding instructions.
			fmt.Fprintf(out, "\tMOVW %d(R19), R21\n\tADDU R20, R%d\n\tXOR R%d, R21\n\tMOVW R21, %d(R18)\n", offset, i+1, i+1, offset)
			continue
		}
		if batch && i == 12 {
			out.WriteString("\tMOVW R25, R21\n")
		} else {
			fmt.Fprintf(out, "\tMOVW %d(R17), R21\n", offset)
		}
		fmt.Fprintf(out, "\tADDU R21, R%d\n", i+1)
		fmt.Fprintf(out, `	MOVWL %d(R19), R21
	MOVWR %d(R19), R21
	XOR R%d, R21
	MOVWL R21, %d(R18)
	MOVWR R21, %d(R18)
`, offset+3, offset, i+1, offset+3, offset)
	}
}
