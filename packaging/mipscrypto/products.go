package main

import (
	"fmt"
	"strings"
)

func productsAssemblySource() string {
	var out strings.Builder
	out.WriteString(`// Code generated by go run ./packaging/mipscrypto -generate; DO NOT EDIT.
//go:build linux && mipsle && gc && !purego

#include "textflag.h"

// One leaf call for all six products; upstream reduction is unchanged.
// c <= 7 and r/s are clamped by upstream initialize. Their products fit uint64.
// No floating point, secret branches or reserved R22/R23/R30 registers.
TEXT ·productsMIPS(SB), NOSPLIT, $-4-136
`)
	for i, product := range []struct{ left, right, result string }{
		{"a", "r", "ar"}, {"b", "r", "br"}, {"c", "r", "cr"},
		{"a", "s", "as"}, {"b", "s", "bs"}, {"c", "s", "cs"},
	} {
		left := strings.Index("abc", product.left) * 8
		right := 24 + strings.Index("rs", product.right)*8
		fmt.Fprintf(&out, "\tMOVW %s_lo+%d(FP), R1\n", product.left, left)
		if product.left != "c" {
			fmt.Fprintf(&out, "\tMOVW %s_hi+%d(FP), R2\n", product.left, left+4)
		}
		fmt.Fprintf(&out, "\tMOVW %s_lo+%d(FP), R3\n\tMOVW %s_hi+%d(FP), R4\n", product.right, right, product.right, right+4)
		if product.left == "c" {
			out.WriteString(`	MULU R3, R1
	MOVW LO, R8
	MOVW HI, R9
	MULU R4, R1
	MOVW LO, R10
	ADDU R10, R9
	MOVW R0, R11
	MOVW R0, R15
`)
		} else {
			out.WriteString(`	MULU R3, R1
	MOVW LO, R8
	MOVW HI, R9
	MULU R4, R1
	MOVW LO, R10
	MOVW HI, R11
	MULU R3, R2
	MOVW LO, R12
	MOVW HI, R13
	MULU R4, R2
	MOVW LO, R14
	MOVW HI, R15
	ADDU R10, R9
	SGTU R10, R9, R16
	ADDU R12, R9
	SGTU R12, R9, R17
	ADDU R17, R16
	ADDU R13, R11
	SGTU R13, R11, R18
	ADDU R14, R11
	SGTU R14, R11, R19
	ADDU R16, R11
	SGTU R16, R11, R20
	ADDU R19, R18
	ADDU R20, R18
	ADDU R18, R15
`)
		}
		for j, part := range []string{"lo_lo", "lo_hi", "hi_lo", "hi_hi"} {
			register := []int{8, 9, 11, 15}[j]
			fmt.Fprintf(&out, "\tMOVW R%d, %s_%s+%d(FP)\n", register, product.result, part, 40+i*16+j*4)
		}
	}
	out.WriteString("\tRET\n")
	return out.String()
}
